"""Assemble the library file the Idea Library app reads, check it, and write it.

The app's own sample library (``system/apps/idea-library/testdata/map-data.json``) is the
contract. On top of it the library may carry two optional fields the pages can read:
``author`` (a display name) and ``chapters`` (``[{name, subtitle}]``, in reading order).

Merging never rewrites what is already there: ideas, connections and sources keep their
fields, hand edits included. The one exception is a source whose text changed: its stored
text is replaced, and quotes of it that no longer appear are dropped (and reported).
"""

from __future__ import annotations

import datetime
import json
import re
import shutil
from pathlib import Path
from typing import Any

from library_sources import slugify

GENERATOR = "build-idea-library"
DEFAULT_TITLE = "Idea Library"
DEFAULT_DISCLAIMER = (
    "Ideas and quotes come from the author's own material; every quote appears word for word in its "
    "source. Connections marked suggested are interpretations, not the author's claims. Positions on "
    "the map are arranged for reading, not a measure of similarity."
)
GENERATED_MARKER = "<!-- generated by build-idea-library -->"
# The optional fields naming whose library it is, which the pages read.
OWNER_FIELDS = ("author", "collection", "reading_intro")
# Map layout: chapters sit in a grid of regions, ideas in a small grid inside each region.
REGION_COLUMNS = 3
REGION_WIDTH = 760
IDEA_COLUMNS = 3
IDEA_DX = 225
IDEA_DY = 135
ORIGIN_X = 160
ORIGIN_Y = 150
REGION_GAP_Y = 210


# ---- the contract ------------------------------------------------------------


def _is_text(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def validate_library(
    data: Any, *, strict_quotes: bool = True
) -> tuple[list[str], list[str]]:
    """(errors, warnings) for a library file.

    Errors break the pages: a missing field, a dangling reference, a duplicate id, a
    wrong type. A quote that does not appear word for word in its source is an error when
    ``strict_quotes`` (what this skill writes), a warning otherwise (a hand-made library)."""
    errors: list[str] = []
    warnings: list[str] = []
    if not isinstance(data, dict):
        return ["the library is not a JSON object"], warnings
    for key in ("nodes", "edges", "sources"):
        if not isinstance(data.get(key), list):
            errors.append(f"'{key}' must be a list")
    if errors:
        return errors, warnings
    for key in ("title", "scope", "disclaimer", *OWNER_FIELDS):
        if key in data and data[key] is not None and not isinstance(data[key], str):
            errors.append(f"'{key}' must be text")
    if "coverage" in data and not isinstance(data["coverage"], dict):
        errors.append("'coverage' must be an object")
    chapter_names: list[str] = []
    if "chapters" in data:
        if not isinstance(data["chapters"], list):
            errors.append("'chapters' must be a list")
        else:
            for i, chapter in enumerate(data["chapters"]):
                if not isinstance(chapter, dict) or not _is_text(chapter.get("name")):
                    errors.append(f"chapters[{i}] needs a 'name'")
                    continue
                if not isinstance(chapter.get("subtitle", ""), str):
                    errors.append(f"chapters[{i}] 'subtitle' must be text")
                if chapter["name"] in chapter_names:
                    errors.append(f"chapter '{chapter['name']}' is listed twice")
                chapter_names.append(chapter["name"])

    sources: dict[str, dict[str, Any]] = {}
    for i, source in enumerate(data["sources"]):
        where = f"sources[{i}]"
        if not isinstance(source, dict) or not _is_text(source.get("id")):
            errors.append(f"{where} needs an 'id'")
            continue
        where = f"source '{source['id']}'"
        if source["id"] in sources:
            errors.append(f"{where} appears twice")
        sources[source["id"]] = source
        for key in ("title", "kind", "url"):
            if not _is_text(source.get(key)):
                errors.append(f"{where} needs '{key}'")
        if not isinstance(source.get("raw"), str):
            errors.append(f"{where} needs its text in 'raw'")
        for key in ("audio", "transcript", "transcription_note", "link_label"):
            if source.get(key) is not None and not isinstance(source[key], str):
                errors.append(f"{where} '{key}' must be text or null")

    def check_evidence(owner: str, evidence: Any, *, required: bool) -> None:
        if not isinstance(evidence, list):
            errors.append(f"{owner} 'evidence' must be a list")
            return
        if required and not evidence:
            errors.append(f"{owner} has no evidence")
        for j, entry in enumerate(evidence):
            if (
                not isinstance(entry, dict)
                or not _is_text(entry.get("quote"))
                or not _is_text(entry.get("source_id"))
            ):
                errors.append(f"{owner} evidence[{j}] needs 'source_id' and 'quote'")
                continue
            source = sources.get(entry["source_id"])
            if source is None:
                errors.append(f"{owner} quotes unknown source '{entry['source_id']}'")
            elif (
                isinstance(source.get("raw"), str)
                and entry["quote"] not in source["raw"]
            ):
                message = (
                    f"{owner} quotes words not found in source '{entry['source_id']}'"
                )
                (errors if strict_quotes else warnings).append(message)
            if "timestamp" in entry and not isinstance(entry["timestamp"], str):
                errors.append(f"{owner} evidence[{j}] 'timestamp' must be text")

    node_ids: set[str] = set()
    groups: list[str] = []
    for i, node in enumerate(data["nodes"]):
        if not isinstance(node, dict) or not _is_text(node.get("id")):
            errors.append(f"nodes[{i}] needs an 'id'")
            continue
        where = f"idea '{node['id']}'"
        if node["id"] in node_ids:
            errors.append(f"{where} appears twice")
        node_ids.add(node["id"])
        for key in ("title", "summary", "group"):
            if not _is_text(node.get(key)):
                errors.append(f"{where} needs '{key}'")
        if _is_text(node.get("group")) and node["group"] not in groups:
            groups.append(node["group"])
        for key in ("x", "y"):
            if not isinstance(node.get(key), (int, float)) or isinstance(
                node.get(key), bool
            ):
                errors.append(f"{where} needs a number '{key}'")
        if node.get("writing_seed") is not None and not isinstance(
            node["writing_seed"], str
        ):
            errors.append(f"{where} 'writing_seed' must be text or null")
        check_evidence(where, node.get("evidence"), required=True)

    edge_ids: set[str] = set()
    for i, edge in enumerate(data["edges"]):
        if not isinstance(edge, dict) or not _is_text(edge.get("id")):
            errors.append(f"edges[{i}] needs an 'id'")
            continue
        where = f"connection '{edge['id']}'"
        if edge["id"] in edge_ids:
            errors.append(f"{where} appears twice")
        edge_ids.add(edge["id"])
        for key in ("source", "target"):
            if edge.get(key) not in node_ids:
                errors.append(f"{where} points at unknown idea '{edge.get(key)}'")
        for key in ("label", "why"):
            if not _is_text(edge.get(key)):
                errors.append(f"{where} needs '{key}'")
        if edge.get("basis") not in ("expressed", "suggested"):
            errors.append(f"{where} 'basis' must be 'expressed' or 'suggested'")
        check_evidence(where, edge.get("evidence", []), required=False)
        if edge.get("basis") == "expressed" and not edge.get("evidence"):
            warnings.append(f"{where} is marked expressed but carries no quote")

    if chapter_names:
        for group in groups:
            if group not in chapter_names:
                warnings.append(
                    f"chapter '{group}' has ideas but no entry in 'chapters'"
                )
    return errors, warnings


# ---- layout ------------------------------------------------------------------


def chapter_order(data: dict[str, Any]) -> list[str]:
    names = [c["name"] for c in data.get("chapters") or []]
    for node in data["nodes"]:
        if node["group"] not in names:
            names.append(node["group"])
    return names


def lay_out(data: dict[str, Any]) -> None:
    """Place every idea in its chapter's region: regions in rows of three, ideas in rows
    of three inside each region, rows of regions spaced by their tallest member."""
    order = chapter_order(data)
    members = {name: [n for n in data["nodes"] if n["group"] == name] for name in order}
    y = ORIGIN_Y
    for row_start in range(0, len(order), REGION_COLUMNS):
        row = order[row_start : row_start + REGION_COLUMNS]
        tallest = 1
        for column, name in enumerate(row):
            for i, node in enumerate(members[name]):
                node["x"] = (
                    ORIGIN_X + column * REGION_WIDTH + (i % IDEA_COLUMNS) * IDEA_DX
                )
                node["y"] = y + (i // IDEA_COLUMNS) * IDEA_DY
            tallest = max(
                tallest, (len(members[name]) + IDEA_COLUMNS - 1) // IDEA_COLUMNS
            )
        y += tallest * IDEA_DY + REGION_GAP_Y


# ---- merging -----------------------------------------------------------------


def empty_library(title: str | None) -> dict[str, Any]:
    return {
        "title": title or DEFAULT_TITLE,
        "scope": "",
        "disclaimer": DEFAULT_DISCLAIMER,
        "coverage": {"scope_generated": True},
        "chapters": [],
        "nodes": [],
        "edges": [],
        "sources": [],
    }


def unique_id(base: str, taken: set[str]) -> str:
    candidate = base
    counter = 2
    while candidate in taken:
        candidate = f"{base}-{counter}"
        counter += 1
    taken.add(candidate)
    return candidate


def library_source(
    record: dict[str, Any],
    asset_url: str | None,
    transcript: str | None,
    audio: str | None,
) -> dict[str, Any]:
    """The library's entry for a stored source record."""
    entry: dict[str, Any] = {
        "id": record["id"],
        "title": record["title"],
        "kind": record["kind"],
        "url": record.get("url") or asset_url or "",
        "raw": record["raw"],
        "audio": audio,
        "transcript": transcript,
    }
    if record.get("transcription_note"):
        entry["transcription_note"] = record["transcription_note"]
    if record.get("date"):
        entry["date"] = record["date"]
    return entry


def refresh_changed_sources(
    data: dict[str, Any], records: dict[str, dict[str, Any]]
) -> dict[str, list[str]]:
    """Bring each library source whose stored text changed up to date, and drop quotes of
    it that no longer appear. Ideas left with no quote go, with their connections."""
    report: dict[str, list[str]] = {
        "stale_quotes": [],
        "removed_ideas": [],
        "removed_connections": [],
    }
    changed: set[str] = set()
    for source in data["sources"]:
        record = records.get(source["id"])
        if (
            record is not None
            and record.get("status") == "ok"
            and source.get("raw") != record["raw"]
        ):
            source["raw"] = record["raw"]
            changed.add(source["id"])
    if not changed:
        return report
    by_id = {s["id"]: s for s in data["sources"]}

    def still_there(entry: dict[str, Any]) -> bool:
        if (
            entry["source_id"] not in changed
            or entry["quote"] in by_id[entry["source_id"]]["raw"]
        ):
            return True
        report["stale_quotes"].append(f"{entry['source_id']}: {entry['quote'][:120]}")
        return False

    kept_nodes = []
    for node in data["nodes"]:
        node["evidence"] = [e for e in node["evidence"] if still_there(e)]
        if node["evidence"]:
            kept_nodes.append(node)
        else:
            report["removed_ideas"].append(node["title"])
    data["nodes"] = kept_nodes
    ids = {n["id"] for n in kept_nodes}
    kept_edges = []
    for edge in data["edges"]:
        edge["evidence"] = [e for e in edge.get("evidence", []) if still_there(e)]
        if edge["source"] in ids and edge["target"] in ids:
            kept_edges.append(edge)
        else:
            report["removed_connections"].append(edge["id"])
    data["edges"] = kept_edges
    return report


def merge(
    data: dict[str, Any],
    *,
    candidates: list[dict[str, Any]],
    organized: dict[str, Any],
    connections: list[dict[str, Any]],
) -> dict[str, Any]:
    """Add sorted candidates and their connections to ``data``.

    Returns the ids of the new ideas and merges, and a map from candidate id to idea id."""
    taken = {n["id"] for n in data["nodes"]}
    by_cid = {c["cid"]: c for c in candidates}
    nodes_by_id = {n["id"]: n for n in data["nodes"]}
    cid_to_node: dict[str, str] = {}
    new_ids: list[str] = []
    merged = 0
    chapters = [dict(c) for c in organized.get("chapters") or []]
    names = [c["name"] for c in chapters]
    for chapter in data.get("chapters") or []:
        if chapter["name"] not in names:
            chapters.insert(len(names), dict(chapter))
            names.append(chapter["name"])
    for placement in organized.get("placements") or []:
        candidate = by_cid.get(placement["cid"])
        if candidate is None:
            continue
        target = placement.get("merge_into")
        if target:
            node_id = cid_to_node.get(target, target)
            node = nodes_by_id.get(node_id)
            if node is not None:
                for entry in candidate["evidence"]:
                    if all(e["quote"] != entry["quote"] for e in node["evidence"]):
                        node["evidence"].append(entry)
                cid_to_node[placement["cid"]] = node_id
                merged += 1
                continue
        node = {
            "id": unique_id(slugify(candidate["title"], limit=48), taken),
            "title": candidate["title"],
            "summary": candidate["summary"],
            "group": placement.get("chapter") or "More ideas",
            "x": 0,
            "y": 0,
            "evidence": candidate["evidence"],
        }
        if candidate.get("writing_seed"):
            node["writing_seed"] = candidate["writing_seed"]
        data["nodes"].append(node)
        nodes_by_id[node["id"]] = node
        cid_to_node[placement["cid"]] = node["id"]
        new_ids.append(node["id"])
        if node["group"] not in names:
            chapters.append({"name": node["group"], "subtitle": ""})
            names.append(node["group"])
    # Keep ideas grouped by chapter in reading order, so the reading page meets chapters in order.
    rank = {name: i for i, name in enumerate(names)}
    data["nodes"].sort(key=lambda n: rank.get(n["group"], len(rank)))
    data["chapters"] = [
        c for c in chapters if any(n["group"] == c["name"] for n in data["nodes"])
    ]
    edge_numbers = [
        int(m.group(1))
        for e in data["edges"]
        if (m := re.fullmatch(r"c-(\d+)", str(e["id"])))
    ]
    next_number = max(edge_numbers, default=0) + 1
    pairs = {frozenset((e["source"], e["target"])) for e in data["edges"]}
    added_edges = 0
    for connection in connections:
        a = cid_to_node.get(connection["source"], connection["source"])
        b = cid_to_node.get(connection["target"], connection["target"])
        if (
            a == b
            or a not in nodes_by_id
            or b not in nodes_by_id
            or frozenset((a, b)) in pairs
        ):
            continue
        pairs.add(frozenset((a, b)))
        data["edges"].append(
            {"id": f"c-{next_number}", **connection, "source": a, "target": b}
        )
        next_number += 1
        added_edges += 1
    return {
        "new_ideas": new_ids,
        "merged": merged,
        "new_connections": added_edges,
        "cid_to_node": cid_to_node,
    }


def describe_scope(data: dict[str, Any]) -> str:
    kinds: dict[str, int] = {}
    for source in data["sources"]:
        kinds[source["kind"]] = kinds.get(source["kind"], 0) + 1
    parts = ", ".join(f"{kind}: {count}" for kind, count in sorted(kinds.items()))
    return (
        f"{len(data['nodes'])} ideas and {len(data['edges'])} connections drawn from {len(data['sources'])} "
        f"sources ({parts or 'none yet'}). Each idea quotes the author's own words; suggested connections "
        "are interpretations."
    )


def finish(
    data: dict[str, Any],
    *,
    title: str | None,
    ingested: int,
    given: dict[str, str | None] | None = None,
    defaults: dict[str, str | None] | None = None,
) -> None:
    """Set the library's descriptive fields: the title when given; ``author``,
    ``collection`` and ``reading_intro`` from ``given`` (the user's own words, which
    replace what is there) or else ``defaults`` (drawn from the material, which only fill
    a field that is empty, so a hand edit stays); the scope when this skill wrote it; and
    the coverage counts."""
    if title:
        data["title"] = title
    data.setdefault("title", DEFAULT_TITLE)
    data.setdefault("disclaimer", DEFAULT_DISCLAIMER)
    for key in OWNER_FIELDS:
        value = (given or {}).get(key)
        if value:
            data[key] = value
        elif not data.get(key) and (defaults or {}).get(key):
            data[key] = (defaults or {})[key]
    coverage = data.setdefault("coverage", {})
    if not data.get("scope") or coverage.get("scope_generated"):
        data["scope"] = describe_scope(data)
        coverage["scope_generated"] = True
    coverage.update(
        {
            "sources_ingested": ingested,
            "sources_in_library": len(data["sources"]),
            "ideas": len(data["nodes"]),
            "connections": len(data["edges"]),
            "last_built": datetime.datetime.now(datetime.UTC).isoformat(
                timespec="seconds"
            ),
        }
    )


def referenced_source_ids(data: dict[str, Any]) -> set[str]:
    ids = set()
    for item in data["nodes"] + data["edges"]:
        for entry in item.get("evidence", []):
            ids.add(entry["source_id"])
    return ids


# ---- files beside the library ------------------------------------------------------


def copy_asset(
    src: Path, library_dir: Path, relative: str, owned: dict[str, str], sha: str
) -> str:
    """Copy ``src`` to ``library_dir/relative`` unless an identical copy is there; record it."""
    target = library_dir / relative
    if owned.get(relative) != sha or not target.exists():
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, target)
    owned[relative] = sha
    return relative


def write_asset_text(
    text: str, library_dir: Path, relative: str, owned: dict[str, str], sha: str
) -> str:
    target = library_dir / relative
    if owned.get(relative) != sha or not target.exists():
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    owned[relative] = sha
    return relative


def prune_assets(
    library_dir: Path, owned: dict[str, str], needed: set[str]
) -> list[str]:
    """Delete files this skill copied that no source needs any more. Files it did not copy
    are never touched."""
    removed = []
    for relative in sorted(set(owned) - needed):
        (library_dir / relative).unlink(missing_ok=True)
        owned.pop(relative)
        removed.append(relative)
    return removed


def may_overwrite(path: Path, marker_check: str) -> bool:
    """A companion file is written only when missing or written by this skill before."""
    if not path.exists():
        return True
    head = path.read_text(encoding="utf-8", errors="replace")[:4000]
    return marker_check in head


def classic_sample(
    data: dict[str, Any], formats: dict[str, list[str]]
) -> dict[str, Any]:
    """The classic view's file: every idea as a content idea with its first quote."""
    sources = [s for s in data["sources"]]
    ideas = []
    for node in data["nodes"]:
        first = node["evidence"][0]
        ideas.append(
            {
                "id": node["id"],
                "title": node["title"],
                "angle": node.get("writing_seed") or node["summary"],
                "theme": node["group"],
                "quote": first["quote"],
                "source_id": first["source_id"],
                "formats": formats.get(node["id"], []),
                "status": "new",
            }
        )
    sample: dict[str, Any] = {
        "generated_by": GENERATOR,
        "title": data.get("title", DEFAULT_TITLE),
        "scope": data.get("scope", ""),
        "note": data.get("scope", ""),
        "defaults": {},
        "unverified_shapes": [],
        "sources": [
            {k: s.get(k) for k in ("id", "title", "kind", "url", "raw")}
            for s in sources
        ],
        "ideas": ideas,
    }
    for key in ("author", "collection"):
        if data.get(key):
            sample[key] = data[key]
    return sample


def corpus_page(
    template: str,
    data: dict[str, Any],
    records: dict[str, dict[str, Any]],
    urls: dict[str, str],
) -> str:
    """The searchable page of every ingested source (the map's "Transcript corpus" link)."""
    ideas_by_source: dict[str, list[str]] = {}
    for node in data["nodes"]:
        for entry in node["evidence"]:
            ideas_by_source.setdefault(entry["source_id"], [])
            if node["id"] not in ideas_by_source[entry["source_id"]]:
                ideas_by_source[entry["source_id"]].append(node["id"])
    rows = []
    for record in sorted(
        records.values(), key=lambda r: (r.get("date") or "", r["title"]), reverse=True
    ):
        rows.append(
            {
                "id": record["id"],
                "title": record["title"],
                "kind": record["kind"],
                "date": record.get("date"),
                "url": urls.get(record["id"], ""),
                "status": record.get("status"),
                "skip_reason": record.get("skip_reason"),
                "text": record["text"],
                "own": record["raw"]
                if record.get("turns") and record["raw"] != record["text"]
                else None,
                "ideas": ideas_by_source.get(record["id"], []),
            }
        )
    payload = json.dumps(
        {
            "title": data.get("title", DEFAULT_TITLE),
            "author": data.get("author") or "",
            "records": rows,
        },
        ensure_ascii=False,
    )
    payload = payload.replace("<", "\\u003c")
    return template.replace("__CORPUS_DATA__", payload)
